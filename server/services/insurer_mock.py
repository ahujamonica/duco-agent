"""Simulated insurer APIs, backed by the policies stored in the database.

Every response carries ``"simulated": true`` and a disclaimer. These endpoints
are a sandbox: they model how an insurer or TPA would answer so the agent
pipeline can be exercised end to end, and they must never be presented as a
real approval. The same handlers are reachable in-process (default) or over
HTTP at ``/mock-insurers/*``.

Outcomes are deterministic functions of the stored policy, the member link,
the service date and the submitted documentation — not of a scenario name.
"""

from __future__ import annotations

import time
import uuid
from datetime import date, datetime
from decimal import Decimal
from typing import Any

from sqlalchemy.orm import Session

from duco_agent.engines.coordination import (
    ClaimInput,
    InsurancePlan,
    LineInput,
    OrderDecision,
    adjudicate_claim,
    money,
)

from ..config import MOCK_INSURERS_LABEL
from ..models import FamilyMember, MockApiLog, MockClaim, Policy, PolicyMember, PolicyVersion
from .accumulators import get_accumulator
from .coverage import plan_from_version

DISCLAIMER = (
    "SIMULATED RESPONSE — generated by the local mock insurer sandbox from the policy record. "
    "It is not a quotation, an approval or a guarantee of payment."
)


def _dec(value: Any) -> Decimal:
    return money(value or 0)


def _iso(value: Any) -> Any:
    if isinstance(value, (date, datetime)):
        return value.isoformat()
    return value


class MockInsurerService:
    def __init__(self, db: Session):
        self.db = db

    # -- lookup -----------------------------------------------------------
    def _policy(self, policy_number: str | None, policy_id: int | None, insurer: str | None) -> Policy | None:
        query = self.db.query(Policy)
        if policy_id:
            return query.filter(Policy.id == policy_id).one_or_none()
        if policy_number:
            found = query.filter(Policy.policy_number == policy_number).one_or_none()
            if found:
                return found
        if insurer:
            return query.filter(Policy.insurer_name.ilike(f"%{insurer}%")).first()
        return None

    def _member(self, policy: Policy, member_id: int | None, member_name: str | None) -> tuple[FamilyMember | None, PolicyMember | None]:
        if member_id:
            member = self.db.get(FamilyMember, member_id)
            if member and member.family_id == policy.family_id:
                link = (
                    self.db.query(PolicyMember)
                    .filter(PolicyMember.policy_id == policy.id, PolicyMember.member_id == member.id)
                    .one_or_none()
                )
                return member, link
        if member_name:
            for member in self.db.query(FamilyMember).filter(FamilyMember.family_id == policy.family_id):
                if member.name.lower().strip() == member_name.lower().strip():
                    link = (
                        self.db.query(PolicyMember)
                        .filter(PolicyMember.policy_id == policy.id, PolicyMember.member_id == member.id)
                        .one_or_none()
                    )
                    return member, link
        return None, None

    def _log(self, endpoint: str, request: dict, response: dict, status_code: int, duration_ms: int) -> None:
        self.db.add(
            MockApiLog(
                case_id=request.get("case_id"),
                endpoint=endpoint,
                method="POST" if "{" not in endpoint else "GET",
                request={k: v for k, v in request.items() if k != "case_id"},
                response=response,
                status_code=status_code,
                simulated=True,
                duration_ms=duration_ms,
            )
        )
        self.db.commit()

    # -- eligibility ------------------------------------------------------
    def eligibility(self, payload: dict) -> dict:
        started = time.perf_counter()
        policy = self._policy(payload.get("policy_number"), payload.get("policy_id"), payload.get("insurer"))
        service_date = payload.get("service_date") or date.today().isoformat()
        response: dict
        if not policy:
            response = {
                "simulated": True,
                "status": "not_found",
                "eligible": False,
                "reason": "No policy with that number exists in the sandbox.",
                "disclaimer": DISCLAIMER,
            }
        else:
            member, link = self._member(policy, payload.get("member_id"), payload.get("member_name"))
            reasons: list[str] = []
            eligible = True
            if policy.status != "active":
                eligible = False
                reasons.append(f"policy status is {policy.status}")
            try:
                when = date.fromisoformat(service_date)
            except ValueError:
                when = date.today()
            if policy.start_date and when < policy.start_date:
                eligible = False
                reasons.append("service date is before the policy started")
            if policy.end_date and when > policy.end_date:
                eligible = False
                reasons.append("service date is after the policy expired")
            if not member:
                eligible = False
                reasons.append("member not found on this policy")
            elif not link:
                eligible = False
                reasons.append(f"{member.name} is not a covered member on this policy")
            version = policy.current_version
            response = {
                "simulated": True,
                "status": "active" if policy.status == "active" else policy.status,
                "eligible": eligible,
                "policy_number": policy.policy_number,
                "insurer": policy.insurer_name,
                "plan_name": policy.plan_name,
                "member": {
                    "id": member.id if member else None,
                    "name": member.name if member else payload.get("member_name"),
                    "role": link.role if link else None,
                },
                "service_date": service_date,
                "member_role": link.role if link else None,
                "reasons": reasons or ["policy is in force and the member is covered"],
                "policy_period": {
                    "start": _iso(policy.start_date),
                    "end": _iso(policy.end_date),
                },
                "network": "network-only" if version and version.network_only else "network and reimbursement",
                "disclaimer": DISCLAIMER,
            }
        duration = int((time.perf_counter() - started) * 1000)
        self._log("POST /mock-insurers/eligibility", payload, response, 200 if policy else 404, duration)
        return response

    # -- benefits ---------------------------------------------------------
    def benefits(self, payload: dict) -> dict:
        started = time.perf_counter()
        policy = self._policy(payload.get("policy_number"), payload.get("policy_id"), payload.get("insurer"))
        if not policy:
            response = {"simulated": True, "status": "not_found", "disclaimer": DISCLAIMER}
            self._log("POST /mock-insurers/benefits", payload, response, 404, 1)
            return response
        version: PolicyVersion = policy.current_version
        member, link = self._member(policy, payload.get("member_id"), payload.get("member_name"))
        if not version:
            response = {"simulated": True, "status": "no_benefits_on_file", "disclaimer": DISCLAIMER}
            self._log("POST /mock-insurers/benefits", payload, response, 200, 1)
            return response
        accumulator = (
            get_accumulator(self.db, policy, version, member.id) if member else None
        )
        ded_used = _dec(accumulator.deductible_used if accumulator else version.deductible_used)
        oop_used = _dec(accumulator.oop_used if accumulator else version.oop_used)
        annual_used = _dec(accumulator.annual_limit_used if accumulator else version.annual_limit_used)
        remaining_deductible = money(max(Decimal("0"), _dec(version.deductible) - ded_used))
        remaining_oop = money(max(Decimal("0"), _dec(version.oop_max) - oop_used))
        remaining_annual = money(max(Decimal("0"), _dec(version.annual_limit) - annual_used))
        response = {
            "simulated": True,
            "status": "active" if policy.status == "active" else policy.status,
            "policy_number": policy.policy_number,
            "insurer": policy.insurer_name,
            "plan_name": policy.plan_name,
            "policy_version": version.version,
            "member": member.name if member else payload.get("member_name"),
            "member_role": link.role if link else None,
            "benefits": {
                "sum_insured": str(_dec(version.sum_insured)),
                "annual_limit": str(_dec(version.annual_limit)),
                "annual_limit_remaining": str(remaining_annual),
                "deductible": str(_dec(version.deductible)),
                "deductible_remaining": str(remaining_deductible),
                "coinsurance_member": str(_dec(version.coinsurance_member)),
                "oop_max": str(_dec(version.oop_max)),
                "oop_remaining": str(remaining_oop),
                "preauth_threshold": str(_dec(version.preauth_threshold)),
                "waiting_period_days": version.waiting_period_days,
                "network_only": bool(version.network_only),
                "exclusions": version.exclusions or [],
                "sublimits": version.sublimits or [],
            },
            "accumulators": {
                "deductible_used": str(ded_used),
                "oop_used": str(oop_used),
                "annual_limit_used": str(annual_used),
                "member_id": member.id if member else None,
            },
            "disclaimer": DISCLAIMER,
        }
        self._log("POST /mock-insurers/benefits", payload, response, 200, int((time.perf_counter() - started) * 1000))
        return response

    # -- claims -----------------------------------------------------------
    def submit_claim(self, payload: dict) -> dict:
        started = time.perf_counter()
        policy = self._policy(payload.get("policy_number"), payload.get("policy_id"), payload.get("insurer"))
        reference = f"MOCK-CLM-{uuid.uuid4().hex[:10].upper()}"
        if not policy:
            response = {
                "simulated": True,
                "status": "rejected",
                "reference": reference,
                "reason": "policy not found in the sandbox",
                "disclaimer": DISCLAIMER,
            }
            self._save_claim(reference, payload, None, None, "rejected", response)
            self._log("POST /mock-insurers/claims", payload, response, 404, 1)
            return response
        version = self.db.get(PolicyVersion, payload["policy_version_id"]) if payload.get("policy_version_id") else policy.current_version
        if not version or version.policy_id != policy.id:
            version = policy.current_version
        member, link = self._member(policy, payload.get("member_id"), payload.get("member_name"))
        service_date = payload.get("service_date")
        try:
            when = date.fromisoformat(service_date) if service_date else date.today()
        except ValueError:
            when = date.today()

        eligibility = self.eligibility(
            {
                "policy_id": policy.id,
                "member_id": member.id if member else payload.get("member_id"),
                "member_name": payload.get("member_name"),
                "service_date": when.isoformat(),
                "case_id": payload.get("case_id"),
            }
        )
        lines_payload = payload.get("lines") or []
        reason = None
        if not eligibility.get("eligible"):
            response = {
                "simulated": True,
                "status": "rejected",
                "reference": reference,
                "reason": "; ".join(eligibility.get("reasons") or []),
                "disclaimer": DISCLAIMER,
            }
            self._save_claim(reference, payload, policy.id, member.id if member else None, "rejected", response)
            self._log("POST /mock-insurers/claims", payload, response, 200, int((time.perf_counter() - started) * 1000))
            return response
        if not lines_payload:
            response = {
                "simulated": True,
                "status": "rejected",
                "reference": reference,
                "reason": "no service lines supplied",
                "disclaimer": DISCLAIMER,
            }
            self._save_claim(reference, payload, policy.id, member.id if member else None, "rejected", response)
            self._log("POST /mock-insurers/claims", payload, response, 200, int((time.perf_counter() - started) * 1000))
            return response

        claim_input = ClaimInput(
            claim_id=int(payload.get("claim_id") or 0),
            patient_name=payload.get("member_name") or (member.name if member else ""),
            member_key=str(member.id if member else ""),
            provider_name=payload.get("provider") or "",
            service_date=when,
            lines=[
                LineInput(
                    line_id=index + 1,
                    description=line.get("description") or f"Line {index + 1}",
                    billed=_dec(line.get("billed") or line.get("amount")),
                    quantity=int(line.get("quantity") or 1),
                    unit_rate=_dec(line.get("unit_rate")),
                    cpt_code=line.get("cpt_code"),
                    icd_codes=line.get("icd_codes") or [],
                    category=line.get("category") or "professional",
                    excluded=bool(line.get("excluded")),
                )
                for index, line in enumerate(lines_payload)
            ],
        )
        accumulator = get_accumulator(self.db, policy, version, member.id) if member else None
        plan: InsurancePlan = plan_from_version(
            policy, version, link, policy.coordination_rule or "policyholder", accumulator
        )
        result = adjudicate_claim(
            claim_input,
            [plan],
            [OrderDecision(plan.key, "primary", 1, policy.coordination_rule or "policyholder")],
            {plan.key: bool(payload.get("preauth_approved"))},
            provider_in_network=bool(payload.get("provider_in_network", True)),
        )
        totals = result.totals
        status = "approved" if totals["insurer_paid"] > 0 else "rejected"
        if totals["insurer_paid"] > 0 and (totals["patient_liability"] > 0 or totals["excluded"] > 0):
            status = "partially_approved"
        response = {
            "simulated": True,
            "status": status,
            "reference": reference,
            "insurer": policy.insurer_name,
            "policy_number": policy.policy_number,
            "policy_version": version.version,
            "member": member.name if member else payload.get("member_name"),
            "service_date": when.isoformat(),
            "allowed_amount": str(totals["allowed"]),
            "deductible_applied": str(result.plans[0].deductible_total),
            "coinsurance_member": str(result.plans[0].coinsurance_total),
            "plan_paid": str(totals["insurer_paid"]),
            "patient_responsibility": str(totals["patient_liability"]),
            "excluded_amount": str(totals["excluded"]),
            "preauth_penalty": str(result.plans[0].penalty_total),
            "lines": [
                {
                    "description": line.description,
                    "billed": str(line.billed),
                    "allowed": str(line.allowed),
                    "plan_paid": str(
                        next((p.plan_paid for p in line.plans), Decimal("0"))
                    ),
                    "patient": str(line.patient),
                }
                for line in result.lines
            ],
            "notes": result.warnings or ["adjudicated under the stored policy terms"],
            "disclaimer": DISCLAIMER,
        }
        self._save_claim(reference, payload, policy.id, member.id if member else None, status, response)
        self._log("POST /mock-insurers/claims", payload, response, 200, int((time.perf_counter() - started) * 1000))
        return response

    def _save_claim(self, reference: str, payload: dict, policy_id, member_id, status: str, response: dict) -> None:
        self.db.add(
            MockClaim(
                reference=reference,
                case_id=payload.get("case_id"),
                policy_id=policy_id,
                member_id=member_id,
                status=status,
                request={k: v for k, v in payload.items() if k != "case_id"},
                response=response,
                simulated=True,
            )
        )
        self.db.commit()

    def get_claim(self, reference: str) -> dict:
        found = self.db.query(MockClaim).filter(MockClaim.reference == reference).one_or_none()
        if not found:
            return {"simulated": True, "status": "not_found", "reference": reference, "disclaimer": DISCLAIMER}
        return found.response

    # -- pre-authorisation ------------------------------------------------
    def pre_authorization(self, payload: dict) -> dict:
        started = time.perf_counter()
        policy = self._policy(payload.get("policy_number"), payload.get("policy_id"), payload.get("insurer"))
        reference = f"MOCK-PA-{uuid.uuid4().hex[:8].upper()}"
        if not policy:
            response = {
                "simulated": True,
                "status": "rejected",
                "reference": reference,
                "reason": "policy not found",
                "disclaimer": DISCLAIMER,
            }
            self._log("POST /mock-insurers/pre-authorization", payload, response, 404, 1)
            return response
        eligibility = self.eligibility(
            {
                "policy_id": policy.id,
                "member_id": payload.get("member_id"),
                "member_name": payload.get("member_name"),
                "service_date": payload.get("service_date") or date.today().isoformat(),
                "case_id": payload.get("case_id"),
            }
        )
        procedure_codes = [str(code) for code in payload.get("procedure_codes") or []]
        diagnosis_codes = [str(code) for code in payload.get("diagnosis_codes") or []]
        documents = payload.get("documents") or []
        estimate = _dec(payload.get("estimated_cost"))
        justification = (payload.get("clinical_justification") or "").strip()
        reasons: list[str] = []
        status = "approved"
        version = policy.current_version
        if not eligibility.get("eligible"):
            status = "rejected"
            reasons.extend(eligibility.get("reasons") or ["member not eligible"])
        if not procedure_codes:
            status = "rejected"
            reasons.append("procedure codes are missing")
        if not diagnosis_codes:
            status = "rejected"
            reasons.append("diagnosis codes are missing")
        if not justification and status != "rejected":
            status = "rejected"
            reasons.append("clinical justification is missing")
        if not estimate or estimate <= 0:
            if status != "rejected":
                status = "pending"
            reasons.append("estimated cost is missing")
        if payload.get("provider_in_network") is False:
            status = "pending"
            reasons.append("provider is out of network; manual review required")
        excluded_codes = {
            str(item.get("code"))
            for item in (version.exclusions if version else [])
            if isinstance(item, dict) and item.get("code")
        }
        hit = set(procedure_codes) & excluded_codes
        if hit:
            status = "rejected"
            reasons.append(f"procedure {', '.join(sorted(hit))} is excluded by the policy")

        if not reasons:
            reasons.append("documentation is complete and the service is covered")
        response = {
            "simulated": True,
            "status": status,
            "reference": reference,
            "insurer": policy.insurer_name,
            "policy_number": policy.policy_number,
            "member": payload.get("member_name"),
            "service_date": payload.get("service_date"),
            "procedure_codes": procedure_codes,
            "diagnosis_codes": diagnosis_codes,
            "estimated_cost": str(estimate),
            "documents_attached": documents,
            "reasons": reasons,
            "valid_until": payload.get("admission_date") or payload.get("service_date"),
            "disclaimer": DISCLAIMER,
        }
        self._log(
            "POST /mock-insurers/pre-authorization", payload, response, 200,
            int((time.perf_counter() - started) * 1000),
        )
        return response
