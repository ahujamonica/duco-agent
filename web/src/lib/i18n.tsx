const dictionaries: Record<Lang, Record<string, string>> = { en, hi };

interface I18nValue {
  lang: Lang;
  setLanguage: (lang: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  tc: (key: string) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(getLang());

  useEffect(() => {
    const listener = () => setLangState(getLang());
    window.addEventListener("duco-lang", listener);
    return () => window.removeEventListener("duco-lang", listener);
  }, []);

  const setLanguage = useCallback((next: Lang) => {
    setLang(next);
    setLangState(next);
    document.documentElement.lang = next;
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let text = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
      if (vars) {
        for (const [name, value] of Object.entries(vars)) {
          text = text.replace(new RegExp(`\\{${name}\\}`, "g"), String(value));
        }
      }
      return text;
    },
    [lang]
  );

  const tc = useCallback(
    (key: string) => dictionaries[lang][key] ?? dictionaries.en[key] ?? key,
    [lang]
  );

  const value = useMemo(() => ({ lang, setLanguage, t, tc }), [lang, setLanguage, t, tc]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
